// Generates lib/design_system/icons/ss_icons.dart from Lucide's codepoints.
//
//   dart run tool/gen_lucide_icons.dart <path/to/lucide-static/font/codepoints.json>
//
// Source: lucide-static 1.61.0 (ISC licence; Feather-derived icons MIT). The
// font is bundled at assets/fonts/lucide/lucide.ttf; the release build
// tree-shakes it to the const icons actually used.
import 'dart:convert';
import 'dart:io';

const _names = '''
chevron-down chevron-right chevron-left chevron-up check minus plus x eye eye-off
lock lock-open search settings undo-2 redo-2 play pause mouse-pointer-2 frame type
square circle hand image layers clapperboard folder file move zoom-in zoom-out
maximize minimize panel-left panel-right panel-bottom keyboard info triangle-alert
circle-check circle-alert pipette copy trash-2 pencil ellipsis arrow-left arrow-right
arrow-up arrow-down align-start-vertical align-center-vertical align-end-vertical
align-start-horizontal align-center-horizontal align-end-horizontal monitor tablet
smartphone link unlink grip-vertical music book-open external-link rotate-ccw
sliders-horizontal scan component command circle-help eye-closed audio-lines film
layout-template mouse-pointer scaling ruler''';

String _camel(String kebab) {
  final parts = kebab.split('-');
  return parts.first +
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}

void main(List<String> args) {
  final cp =
      jsonDecode(File(args.first).readAsStringSync()) as Map<String, Object?>;
  final names = _names.split(RegExp(r'\s+'))..sort();
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_lucide_icons.dart - do not edit.')
    ..writeln('// Lucide icons (lucide-static 1.61.0), ISC licence; see')
    ..writeln('// assets/fonts/lucide/LICENSE.txt.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('/// The Lucide icons the editor chrome uses, as const [IconData]')
    ..writeln('/// (so the release build can tree-shake the bundled font).')
    ..writeln('abstract final class SsIcons {')
    ..writeln("  static const String fontFamily = 'Lucide';")
    ..writeln();
  for (final n in names) {
    final code = cp[n]! as int;
    b.writeln(
      '  static const IconData ${_camel(n)} = IconData(0x${code.toRadixString(16)}, fontFamily: fontFamily);',
    );
  }
  b.writeln('}');
  File('lib/design_system/icons/ss_icons.dart').writeAsStringSync(b.toString());
}
